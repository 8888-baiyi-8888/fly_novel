/** 演示/测试用：合并内置 AI 红线后的书籍规则（R01-R07 + A01-A11）。 */
export function buildExampleBookRules(): BookRules {
  const rules = [
    "叶凡的行为必须符合谨慎、克制的性格。",
    "叶凡的真实身份前期不得揭示，身份信息只能通过旁侧细节释放。",
    "反派江辰的行为必须有自洽逻辑，禁止降智。",
    "灭门案的细节信息由闪回线逐段释放，不得一次性倾倒。",
    "爽点必须建立在「信息差」结构上，不靠主角直接炫力。",
    "终局信息（龙王身份、灭门真相）不得在前期正文出现。",
    "前期节奏为「压迫→暗燃」，不允许连续高强度爽点。",
  ];
  const AI = [
    "禁黑名单句式：「不是…而是…」「最…最…」「是…更是…」",
    "禁身体反应套话：瞳孔缩成针尖、指节泛白、眼眶微红、喉结滚了滚、空气仿佛凝固、时间仿佛静止",
    "禁水镜系比喻：声音像镜子/湖面/冰碴子、眼神像碎镜/结冰湖面",
    "禁车轱辘话：「你来了/我来了/你不怕死/没有人不怕死」等无信息量往返对话",
    "禁过度解释：「他的眼睛红了，不是哭过的那种红，而是熬夜的红」这类给读者划重点的句子",
    "禁凭空新增：正文不得出现前文不存在的人物、物品、往事、设定；新设定必须先登记再入文",
    "禁混提示词：正文不得混入提示词、设定说明、括号指令",
    "禁书面语连接词滥用：然而/因此/此外/值得注意的是/不难发现/可想而知/让我们看看，每章合计 ≤3 次",
    "禁模糊情绪标签：「心中五味杂陈」「说不出的味道」等，情绪必须落到具体动作或感官",
    "禁止三段连续句子长度相同；禁止每段都以「他/她」开头",
    "禁套路化比喻/拟物：「像一株向日葵」「像太阳/光」「融化坚冰/冰冷的心」「眼里有光/有星星」「心像被什么填满」等万能比喻；比喻必须贴合角色独有的记忆与经历，否则直接删除",
  ];
  return {
    bookId: "yinlong",
    title: "隐龙",
    rules: [
      ...rules.map((content, index) => ({
        id: `R${String(index + 1).padStart(2, "0")}`,
        category: "story" as const,
        content,
      })),
      ...AI.map((content, index) => ({
        id: `A${String(index + 1).padStart(2, "0")}`,
        category: "ai-redline" as const,
        content,
      })),
    ],
  };
}
